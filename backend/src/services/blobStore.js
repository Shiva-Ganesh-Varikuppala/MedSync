// Where uploaded files are kept (the "non-relational" half of MedSync: files, not rows).
//   AZURE_STORAGE_CONNECTION_STRING set -> Azure Blob Storage, in the private container AZURE_STORAGE_CONTAINER
//   not set                              -> a local folder (BLOB_LOCAL_DIR, default backend/uploads), for development
// Callers use put / get / remove with a blob name and never care which one is behind it.
const fs = require("fs/promises");
const path = require("path");

const container = () => process.env.AZURE_STORAGE_CONTAINER || "prescription-files";
const azureConfigured = () => Boolean(process.env.AZURE_STORAGE_CONNECTION_STRING);
const localDir = () => process.env.BLOB_LOCAL_DIR || path.join(__dirname, "..", "..", "uploads");

let azureClient = null, azureKey = "";
async function azure() {
    const key = `${process.env.AZURE_STORAGE_CONNECTION_STRING}|${container()}`;
    if (azureClient && azureKey === key) return azureClient;
    const { BlobServiceClient } = require("@azure/storage-blob"); // only loaded when Azure is used
    const client = BlobServiceClient.fromConnectionString(process.env.AZURE_STORAGE_CONNECTION_STRING).getContainerClient(container());
    await client.createIfNotExists(); // the container is private: no public access level is given
    azureClient = client; azureKey = key;
    return client;
}

// Blob names are generated by the server, but the local driver still refuses anything that could leave its folder.
function localPath(name) {
    const full = path.resolve(localDir(), name);
    if (!full.startsWith(path.resolve(localDir()) + path.sep)) throw new Error("Invalid blob name");
    return full;
}

async function put(name, buffer, contentType) {
    if (azureConfigured()) {
        const client = await azure();
        await client.getBlockBlobClient(name).uploadData(buffer, { blobHTTPHeaders: { blobContentType: contentType } });
        return;
    }
    const file = localPath(name);
    await fs.mkdir(path.dirname(file), { recursive: true });
    await fs.writeFile(file, buffer);
}

async function get(name) {
    if (azureConfigured()) return (await azure()).getBlockBlobClient(name).downloadToBuffer();
    return fs.readFile(localPath(name));
}

async function remove(name) {
    if (azureConfigured()) { await (await azure()).getBlockBlobClient(name).deleteIfExists(); return; }
    await fs.rm(localPath(name), { force: true });
}

// For the admin screen. Never includes the connection string.
const status = () => azureConfigured() ? { driver: "azure-blob", container: container() } : { driver: "local-folder", container: null };

module.exports = { get, put, remove, status };
